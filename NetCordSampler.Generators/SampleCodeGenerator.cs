using System.Text;
using System.Text.Json;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace NetCordSampler.Generators;

/// <summary>
/// Generates sample metadata, code sample implementations, and locators from SamplerTypes.json.
/// </summary>
[Generator]
public class SampleCodeGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var configFiles = context.AdditionalTextsProvider
            .Where(file => file.Path.EndsWith("appsettings.json", StringComparison.OrdinalIgnoreCase))
            .Select((file, ct) => file.GetText(ct)?.ToString())
            .Collect();

        var jsonFiles = context.AdditionalTextsProvider
            .Where(file => file.Path.EndsWith("SamplerTypes.json", StringComparison.OrdinalIgnoreCase))
            .Select((file, ct) => file.GetText(ct)?.ToString())
            .Collect();

        var combined = configFiles.Combine(jsonFiles);

        context.RegisterSourceOutput(combined, (ctx, data) =>
        {
            var (configArray, contentArray) = data;
            
            var config = configArray.FirstOrDefault();
            var content = contentArray.FirstOrDefault();
            
            if (string.IsNullOrWhiteSpace(content))
                return;

            try
            {
                var metadata = ParseMetadata(content!);
                var defaultsConfig = ParseDefaultsConfig(config);
                
                GenerateMetadataClasses(ctx, metadata);
                GenerateSampleImplementations(ctx, metadata, defaultsConfig);
                GenerateSampleLocator(ctx, metadata);
                GenerateHelperMethods(ctx, metadata);
            }
            catch (Exception ex)
            {
                ctx.ReportDiagnostic(Diagnostic.Create(
                    new DiagnosticDescriptor(
                        "NCSGEN001",
                        "Failed to generate sample code",
                        $"Error generating sample code: {ex.Message}",
                        "NetCordSampler.Generators",
                        DiagnosticSeverity.Error,
                        true),
                    Location.None));
            }
        });
    }

    private static SamplerMetadata ParseMetadata(string jsonContent)
    {
        var options = new JsonSerializerOptions 
        { 
            PropertyNameCaseInsensitive = true,
            ReadCommentHandling = JsonCommentHandling.Skip
        };
        
        return JsonSerializer.Deserialize<SamplerMetadata>(jsonContent, options) 
            ?? new SamplerMetadata { Types = [] };
    }

    private static SampleDefaultsConfig? ParseDefaultsConfig(string? jsonContent)
    {
        if (string.IsNullOrWhiteSpace(jsonContent))
            return null;

        try
        {
            var options = new JsonSerializerOptions 
            { 
                PropertyNameCaseInsensitive = true,
                ReadCommentHandling = JsonCommentHandling.Skip
            };
            
            var root = JsonSerializer.Deserialize<JsonElement>(jsonContent!, options);
            if (root.TryGetProperty("SampleDefaults", out var sampleDefaultsElement))
            {
                return JsonSerializer.Deserialize<SampleDefaultsConfig>(sampleDefaultsElement.GetRawText(), options);
            }
        }
        catch
        {
            // If config parsing fails, continue without it
        }

        return null;
    }

    private static void GenerateMetadataClasses(SourceProductionContext context, SamplerMetadata metadata)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated />");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("using System.Collections.Immutable;");
        sb.AppendLine();
        sb.AppendLine("namespace NetCordSampler.Generated;");
        sb.AppendLine();
        
        sb.AppendLine("public record TypeMetadata");
        sb.AppendLine("{");
        sb.AppendLine("    public required string FullName { get; init; }");
        sb.AppendLine("    public required string Namespace { get; init; }");
        sb.AppendLine("    public required string Name { get; init; }");
        sb.AppendLine("    public required string Category { get; init; }");
        sb.AppendLine("    public required string Description { get; init; }");
        sb.AppendLine("    public string SourceSummary { get; init; } = string.Empty;");
        sb.AppendLine("    public ImmutableArray<PropertyMetadata> Properties { get; init; } = [];");
        sb.AppendLine("    public ImmutableArray<Limitation> Limitations { get; init; } = [];");
        sb.AppendLine("}");
        sb.AppendLine();
        
        sb.AppendLine("public record PropertyMetadata");
        sb.AppendLine("{");
        sb.AppendLine("    public required string Name { get; init; }");
        sb.AppendLine("    public required string Type { get; init; }");
        sb.AppendLine("    public string Description { get; init; } = string.Empty;");
        sb.AppendLine("    public string SourceSummary { get; init; } = string.Empty;");
        sb.AppendLine("    public string? ConfigKey { get; init; }");
        sb.AppendLine("    public string? DefaultValue { get; init; }");
        sb.AppendLine("    public bool NestedSample { get; init; }");
        sb.AppendLine("    public string? CollectionOf { get; init; }");
        sb.AppendLine("    public int? DefaultCount { get; init; }");
        sb.AppendLine("    public int? MaxLength { get; init; }");
        sb.AppendLine("    public ImmutableArray<Limitation> Limitations { get; init; } = [];");
        sb.AppendLine("}");
        sb.AppendLine();
        
        sb.AppendLine("public record Limitation");
        sb.AppendLine("{");
        sb.AppendLine("    public required string Name { get; init; }");
        sb.AppendLine("    public string Description { get; init; } = string.Empty;");
        sb.AppendLine("    public string Value { get; init; } = string.Empty;");
        sb.AppendLine("    public int Min { get; init; }");
        sb.AppendLine("    public int Max { get; init; }");
        sb.AppendLine("}");
        sb.AppendLine();
        
        sb.AppendLine("public static partial class SampleMetadata");
        sb.AppendLine("{");
        sb.AppendLine("    public static readonly ImmutableArray<TypeMetadata> AllTypes =");
        sb.AppendLine("    [");
        
        foreach (var type in metadata.Types)
        {
            var parts = type.FullType.Split('.');
            var typeName = parts[parts.Length - 1];
            var typeNamespace = string.Join(".", parts.Take(parts.Length - 1));
            
            sb.AppendLine("        new TypeMetadata");
            sb.AppendLine("        {");
            sb.AppendLine($"            FullName = \"{type.FullType}\",");
            sb.AppendLine($"            Namespace = \"{typeNamespace}\",");
            sb.AppendLine($"            Name = \"{typeName}\",");
            sb.AppendLine($"            Category = \"{type.Category}\",");
            sb.AppendLine($"            Description = \"{EscapeString(type.Description)}\",");
            sb.AppendLine($"            SourceSummary = \"{EscapeString(type.SourceSummary ?? "")}\",");
            
            if (type.Properties?.Length > 0)
            {
                sb.AppendLine("            Properties =");
                sb.AppendLine("            [");
                foreach (var prop in type.Properties)
                {
                    sb.AppendLine("                new PropertyMetadata");
                    sb.AppendLine("                {");
                    sb.AppendLine($"                    Name = \"{prop.Name}\",");
                    sb.AppendLine($"                    Type = \"{prop.Type}\",");
                    sb.AppendLine($"                    Description = \"{EscapeString(prop.Description ?? "")}\",");
                    sb.AppendLine($"                    SourceSummary = \"{EscapeString(prop.SourceSummary ?? "")}\",");
                    if (!string.IsNullOrEmpty(prop.ConfigKey))
                        sb.AppendLine($"                    ConfigKey = \"{prop.ConfigKey}\",");
                    if (!string.IsNullOrEmpty(prop.DefaultValue))
                        sb.AppendLine($"                    DefaultValue = \"{EscapeString(prop.DefaultValue!)}\",");
                    if (prop.NestedSample)
                        sb.AppendLine($"                    NestedSample = true,");
                    if (!string.IsNullOrEmpty(prop.CollectionOf))
                        sb.AppendLine($"                    CollectionOf = \"{prop.CollectionOf}\",");
                    if (prop.DefaultCount.HasValue)
                        sb.AppendLine($"                    DefaultCount = {prop.DefaultCount},");
                    if (prop.MaxLength.HasValue)
                        sb.AppendLine($"                    MaxLength = {prop.MaxLength},");
                    sb.AppendLine("                },");
                }
                sb.AppendLine("            ],");
            }
            
            if (type.Limitations?.Length > 0)
            {
                sb.AppendLine("            Limitations =");
                sb.AppendLine("            [");
                foreach (var limit in type.Limitations)
                {
                    sb.AppendLine("                new Limitation");
                    sb.AppendLine("                {");
                    sb.AppendLine($"                    Name = \"{limit.Name}\",");
                    sb.AppendLine($"                    Description = \"{EscapeString(limit.Description ?? "")}\",");
                    sb.AppendLine($"                    Value = \"{limit.Value ?? ""}\",");
                    sb.AppendLine($"                    Min = {limit.Min},");
                    sb.AppendLine($"                    Max = {limit.Max}");
                    sb.AppendLine("                },");
                }
                sb.AppendLine("            ]");
            }
            
            sb.AppendLine("        },");
        }
        
        sb.AppendLine("    ];");
        sb.AppendLine();
        sb.AppendLine("    public static readonly ImmutableDictionary<string, TypeMetadata> TypesByFullName =");
        sb.AppendLine("        AllTypes.ToImmutableDictionary(t => t.FullName, StringComparer.Ordinal);");
        sb.AppendLine();
        sb.AppendLine("    public static readonly ImmutableDictionary<string, TypeMetadata> TypesByName =");
        sb.AppendLine("        AllTypes.ToImmutableDictionary(t => t.Name, StringComparer.Ordinal);");
        sb.AppendLine("}");
        
        context.AddSource("SampleMetadata.g.cs", SourceText.From(sb.ToString(), Encoding.UTF8));
    }

    private static void GenerateSampleImplementations(SourceProductionContext context, SamplerMetadata metadata, SampleDefaultsConfig? defaultsConfig)
    {
        // Create a hashset of known type names for quick lookup (excluding problematic types)
        var knownTypes = new HashSet<string>(
            metadata.Types
                .Where(t => !t.FullType.EndsWith("MessageReferenceProperties"))
                .Select(t => t.FullType), 
            StringComparer.Ordinal);

        foreach (var type in metadata.Types)
        {
            var parts = type.FullType.Split('.');
            var typeName = parts[parts.Length - 1];
            var typeNamespace = string.Join(".", parts.Take(parts.Length - 1));
            var currentFullType = type.FullType;
            
            // Skip MessageReferenceProperties - has complex constructor requirements not detected by extractor
            if (typeName == "MessageReferenceProperties")
                continue;
            
            var sb = new StringBuilder();
            sb.AppendLine("// <auto-generated />");
            sb.AppendLine("#nullable enable");
            sb.AppendLine($"using {typeNamespace};");
            sb.AppendLine("using NetCordSampler;");
            sb.AppendLine("using NetCordSampler.CodeSamples;");
            sb.AppendLine();
            sb.AppendLine("namespace NetCordSampler.Generated.Samples;");
            sb.AppendLine();
            sb.AppendLine($"public sealed class {typeName}Sample : CodeSampleBase<{typeName}>");
            sb.AppendLine("{");
            
            // CreateDefault method
            sb.AppendLine("    public override " + typeName + " CreateDefault()");
            sb.AppendLine("    {");

            // Check if type has required constructor parameters
            var hasConstructorParams = type.ConstructorParams?.Length > 0;
            var requiredParams = type.ConstructorParams?
                .Where(p => !p.HasDefaultValue)
                .ToList() ?? [];

            if (requiredParams.Count > 0)
            {
                sb.Append($"        return new {typeName}(");
                
                var constructorArgs = new List<string>();
                foreach (var param in requiredParams)
                {
                    var value = GenerateConstructorParamValue(param, knownTypes, currentFullType, defaultsConfig);
                    constructorArgs.Add(value);
                }
                
                sb.Append(string.Join(", ", constructorArgs));
                sb.AppendLine(")");

                var propertiesToSet = type.Properties?
                    .Where(p => !IsConstructorParameter(p, requiredParams))
                    .Where(p => !IsReadOnlyProperty(p))
                    .ToList() ?? [];

                if (propertiesToSet.Count > 0)
                {
                    var propsWithDefaults = new List<string>();
                    foreach (var prop in propertiesToSet)
                    {
                        var value = GenerateDefaultValue(prop, knownTypes, currentFullType, defaultsConfig);
                        if (!value.Contains("default(") && value != "null")
                        {
                            propsWithDefaults.Add($"            {prop.Name} = {value}");
                        }
                    }
                    
                    if (propsWithDefaults.Count > 0)
                    {
                        sb.AppendLine("        {");
                        foreach (var propLine in propsWithDefaults)
                        {
                            sb.AppendLine($"{propLine},");
                        }
                        sb.AppendLine("        };");
                    }
                    else
                    {
                        sb.AppendLine("        ;");
                    }
                }
                else
                {
                    sb.AppendLine("        ;");
                }
            }
            else
            {
                sb.AppendLine($"        return new {typeName}");
                
                var propsWithDefaults = new List<string>();
                if (type.Properties != null)
                {
                    foreach (var prop in type.Properties)
                    {
                        if (IsReadOnlyProperty(prop))
                            continue;

                        var value = GenerateDefaultValue(prop, knownTypes, currentFullType, defaultsConfig);
                        // Skip properties that would be set to null (default for reference types)
                        if (!value.Contains("default(") && value != "null")
                        {
                            propsWithDefaults.Add($"            {prop.Name} = {value}");
                        }
                    }
                }
                
                if (propsWithDefaults.Count > 0)
                {
                    sb.AppendLine("        {");
                    foreach (var propLine in propsWithDefaults)
                    {
                        sb.AppendLine($"{propLine},");
                    }
                    sb.AppendLine("        };");
                }
                else
                {
                    sb.AppendLine("        { };");
                }
            }

            sb.AppendLine("    }");
            sb.AppendLine();
            
            sb.AppendLine($"    public override bool IsEmpty({typeName} instance)");
            sb.AppendLine("    {");
            sb.AppendLine("        ArgumentNullException.ThrowIfNull(instance);");
            sb.AppendLine();
            sb.AppendLine("        return");
            
            if (type.Properties != null && type.Properties.Length > 0)
            {
                for (int i = 0; i < type.Properties.Length; i++)
                {
                    var prop = type.Properties[i];
                    var check = GenerateEmptyCheck(prop);
                    var connector = i < type.Properties.Length - 1 ? " &&" : ";";
                    sb.AppendLine($"            {check}{connector}");
                }
            }
            else
            {
                sb.AppendLine("            false;");
            }
            
            sb.AppendLine("    }");
            sb.AppendLine("}");
            
            context.AddSource($"{typeName}Sample.g.cs", SourceText.From(sb.ToString(), Encoding.UTF8));
        }
    }

    private static string GenerateDefaultValue(PropertyMetadataDto prop, HashSet<string> knownTypes, string currentTypeName, SampleDefaultsConfig? defaultsConfig)
    {
        if (!string.IsNullOrEmpty(prop.DefaultValue))
            return prop.DefaultValue!;
        
        if (!string.IsNullOrEmpty(prop.ConfigKey) && defaultsConfig != null)
        {
            if (defaultsConfig.PatternDefaults.TryGetValue(prop.ConfigKey!, out var configValue))
                return $"\"{configValue}\"";
        }
        
        if (prop.NestedSample)
        {
            var typeParts = prop.Type.Split('.');
            var nestedType = typeParts[typeParts.Length - 1];
            
            if (prop.Type == currentTypeName)
                return $"default({prop.Type})";
            
            if (knownTypes.Contains(prop.Type))
                return $"new {nestedType}Sample().CreateDefault()";
            else
                return $"default({prop.Type})";
        }
        
        if (!string.IsNullOrEmpty(prop.CollectionOf))
        {
            // Handle interface types with concrete implementations
            if (prop.CollectionOf == "NetCord.Rest.IComponentContainerComponentProperties")
            {
                // Define valid component types that can be used in ComponentContainer
                // Based on Discord's component system, these are the display component types
                var validComponentTypes = new[]
                {
                    "NetCord.Rest.TextDisplayProperties",
                    "NetCord.Rest.FileDisplayProperties",
                    "NetCord.Rest.ComponentSeparatorProperties",
                    "NetCord.Rest.MediaGalleryProperties",
                    "NetCord.Rest.ComponentSectionThumbnailProperties"
                }.Where(t => knownTypes.Contains(t)).ToArray();
                
                if (validComponentTypes.Length > 0)
                {
                    var count = prop.DefaultCount ?? 2;
                    var items = new List<string>();
                    
                    // Use index-based pseudo-random selection for deterministic but varied results
                    for (int i = 0; i < count; i++)
                    {
                        var selectedType = validComponentTypes[i % validComponentTypes.Length];
                        var typeParts = selectedType.Split('.');
                        var elementType = typeParts[typeParts.Length - 1];
                        items.Add($"new {elementType}Sample().CreateDefault()");
                    }
                    
                    return $"[{string.Join(", ", items)}]";
                }
                else
                {
                    return "[]";
                }
            }
            
            var concreteType = prop.CollectionOf;
            
            // Check for self-referential collections - avoid infinite recursion
            if (concreteType == currentTypeName)
                return "[]";
            
            // Only try to create sample if the element type exists in our known types
            if (knownTypes.Contains(concreteType!))
            {
                var typeParts = concreteType!.Split('.');
                var elementType = typeParts[typeParts.Length - 1];
                var count = prop.DefaultCount ?? 2;
                var items = new List<string>();
                for (int i = 0; i < count; i++)
                    items.Add($"new {elementType}Sample().CreateDefault()");
                return $"[{string.Join(", ", items)}]";
            }
            else
            {
                return "[]";
            }
        }
        
        // Defaults by type
        return prop.Type switch
        {
            "string" => "string.Empty",
            "int" => "0",
            "bool" => "false",
            _ when prop.Type.EndsWith("?") => "null",
            _ => $"default({prop.Type})"
        };
    }

    private static string GenerateConstructorParamValue(ConstructorParamDto param, HashSet<string> knownTypes, string currentTypeName, SampleDefaultsConfig? defaultsConfig)
    {
        // Try to match the parameter type with common patterns
        var type = param.Type;
        var name = param.Name;

        // Handle interface parameters by using the first concrete implementation
        if (param.InterfaceImplementations != null && param.InterfaceImplementations.Count > 0)
        {
            // Filter out self-references to prevent infinite recursion
            var validImplementations = param.InterfaceImplementations
                .Where(impl => impl != currentTypeName)
                .ToList();
            
            // If we have IEnumerable parameter, return empty collection to avoid recursion issues
            if (type.Contains("IEnumerable"))
                return "[]";
            
            // Use first valid implementation that's not self-referencing
            if (validImplementations.Count > 0)
            {
                var firstImpl = validImplementations[0];
                var typeParts = firstImpl.Split('.');
                var typeName = typeParts[typeParts.Length - 1];
                return $"new {typeName}Sample().CreateDefault()";
            }
            
            // No valid implementations found, return default for the interface type
            return $"default({type})";
        }

        // Check for self-referential collections
        if (type.Contains("IEnumerable") && type.Contains(currentTypeName))
            return "[]";
        
        if (type.Contains("IEnumerable"))
            return "[]";
        
        // All string parameters should have a default value
        if (type == "System.String" || type == "string")
        {
            // Use configuration if available
            if (defaultsConfig != null)
            {
                // Whitelist of safe patterns (must match MetadataExtractor)
                var safePatterns = new HashSet<string>(StringComparer.OrdinalIgnoreCase)
                {
                    "Name", "Title", "Description", "Label", "Text", "Content", "FileName",
                    "Url", "ImageUrl", "ThumbnailUrl", "IconUrl", "AvatarUrl",
                    "Nickname", "Username", "ThreadName", "Topic", "Location",
                    "Placeholder", "EmojiName", "UnicodeIcon", "RtcRegion",
                    "PlatformUsername", "CommandName"
                };

                // Check exact name match
                if (safePatterns.Contains(name) && defaultsConfig.PatternDefaults.TryGetValue(name, out var exactMatch))
                    return $"\"{exactMatch}\"";

                // Check ending patterns (sorted by length descending for specificity)
                var sortedPatterns = safePatterns.OrderByDescending(p => p.Length).ToList();
                foreach (var pattern in sortedPatterns)
                {
                    if (name.EndsWith(pattern, StringComparison.OrdinalIgnoreCase) && 
                        defaultsConfig.PatternDefaults.ContainsKey(pattern))
                    {
                        return $"\"{defaultsConfig.PatternDefaults[pattern]}\"";
                    }
                }

            }

            // Final fallback for strings without pattern match
            return "\"Sample\"";
        }

        // Special cases that can't be in config
        if (type == "System.IO.Stream" || type.EndsWith(".Stream"))
            return "System.IO.Stream.Null";

        // Handle ReadOnlyMemory<byte> for image data
        if (type.Contains("ReadOnlyMemory<System.Byte>") || type.Contains("ReadOnlyMemory<byte>"))
            return "System.ReadOnlyMemory<byte>.Empty";

        // Only return null for nullable types (? suffix) or if the parameter explicitly has a null default
        if (type.EndsWith("?") && param.HasDefaultValue && param.DefaultValue == null)
            return "null";

        // Check if this is a known type in our metadata - create a sample instance
        if (knownTypes.Contains(type))
        {
            var typeParts = type.Split('.');
            var simpleTypeName = typeParts[typeParts.Length - 1];
            return $"new {simpleTypeName}Sample().CreateDefault()";
        }

        // Handle common NetCord enums with meaningful defaults
        if (type.Contains("ImageFormat"))
            return "NetCord.ImageFormat.Png";
        if (type.Contains("ComponentType"))
            return "NetCord.ComponentType.ActionRow";
        if (type.Contains("ButtonStyle"))
            return "NetCord.ButtonStyle.Primary";
        
        // Handle NetCord.EmojiProperties - can use default (struct)
        // According to Discord API, emoji is optional on buttons despite constructor signature
        if (type == "NetCord.EmojiProperties")
            return "default";

        // For nullable types, return null
        if (type.EndsWith("?"))
            return "null";
        
        // For reference types that aren't known, return null with suppression
        // This indicates a missing type that should be added to the metadata
        if (!type.Contains("System.") && (type.Contains("NetCord.") || type.Contains(".Properties")))
            return $"default({type})!";

        // For enum types or complex types, use default
        return $"default({type})";
    }

    private static bool IsConstructorParameter(PropertyMetadataDto prop, List<ConstructorParamDto> ctorParams)
    {
        return ctorParams.Any(p => 
            p.Name.Equals(prop.Name, StringComparison.OrdinalIgnoreCase));
    }

    private static bool IsReadOnlyProperty(PropertyMetadataDto prop)
    {
        // Known read-only properties in NetCord
        var readOnlyProps = new[] 
        { 
            "ComponentType", 
            "Style", 
            "SupportsHttpSerialization" 
        };

        return readOnlyProps.Contains(prop.Name);
    }

    private static string GenerateEmptyCheck(PropertyMetadataDto prop)
    {
        var propAccess = $"instance.{prop.Name}";
        
        return prop.Type switch
        {
            "string" => $"string.IsNullOrEmpty({propAccess})",
            "int" => $"{propAccess} == 0",
            "bool" => $"!{propAccess}",
            _ when prop.Type.EndsWith("?") => $"{propAccess} == null",
            _ when !string.IsNullOrEmpty(prop.CollectionOf) => $"({propAccess} == null || !{propAccess}.Any())",
            _ when prop.Type.Contains("Color") => $"{propAccess}.RawValue == 0",
            _ when prop.Type.Contains("ImageProperties") => "false", // ImageProperties is always considered non-empty since we use default
            _ when prop.Type.Contains("ReadOnlyMemory") => $"{propAccess}.IsEmpty",
            _ => $"{propAccess} == default({prop.Type})"
        };
    }
    private static void GenerateSampleLocator(SourceProductionContext context, SamplerMetadata metadata)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated />");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("using System.Collections.Frozen;");
        sb.AppendLine("using NetCordSampler.Interfaces;");
        sb.AppendLine("using NetCordSampler.Generated.Samples;");
        sb.AppendLine();
        
        // Add usings for all NetCord namespaces
        var namespaces = metadata.Types
            .Select(t => string.Join(".", t.FullType.Split('.').Take(t.FullType.Split('.').Length - 1)))
            .Distinct()
            .OrderBy(ns => ns);
        
        foreach (var ns in namespaces)
            sb.AppendLine($"using {ns};");
        
        sb.AppendLine();
        sb.AppendLine("namespace NetCordSampler.Generated;");
        sb.AppendLine();
        sb.AppendLine("public static partial class CodeSampleLocator");
        sb.AppendLine("{");
        sb.AppendLine("    private static readonly FrozenDictionary<Type, ICodeSample> _samplesByType;");
        sb.AppendLine("    private static readonly FrozenDictionary<string, ICodeSample> _samplesByName;");
        sb.AppendLine();
        sb.AppendLine("    static CodeSampleLocator()");
        sb.AppendLine("    {");
        sb.AppendLine("        var typeDict = new Dictionary<Type, ICodeSample>();");
        sb.AppendLine("        var nameDict = new Dictionary<string, ICodeSample>(StringComparer.Ordinal);");
        sb.AppendLine();
        
        foreach (var type in metadata.Types)
        {
            var parts = type.FullType.Split('.');
            var typeName = parts[parts.Length - 1];
            
            // Skip MessageReferenceProperties
            if (typeName == "MessageReferenceProperties")
                continue;
            
            sb.AppendLine($"        {{");
            sb.AppendLine($"            var sample = new {typeName}Sample();");
            sb.AppendLine($"            typeDict[typeof({typeName})] = sample;");
            sb.AppendLine($"            nameDict[\"{typeName}\"] = sample;");
            sb.AppendLine($"        }}");
        }
        
        sb.AppendLine();
        sb.AppendLine("        _samplesByType = typeDict.ToFrozenDictionary();");
        sb.AppendLine("        _samplesByName = nameDict.ToFrozenDictionary();");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    public static ICodeSample<T>? GetCodeSample<T>()");
        sb.AppendLine("    {");
        sb.AppendLine("        return _samplesByType.TryGetValue(typeof(T), out var sample)");
        sb.AppendLine("            ? sample as ICodeSample<T>");
        sb.AppendLine("            : null;");
        sb.AppendLine("    }");
        sb.AppendLine();
        sb.AppendLine("    public static ICodeSample? GetCodeSample(string typeName)");
        sb.AppendLine("    {");
        sb.AppendLine("        ArgumentException.ThrowIfNullOrWhiteSpace(typeName);");
        sb.AppendLine("        return _samplesByName.GetValueOrDefault(typeName);");
        sb.AppendLine("    }");
        sb.AppendLine("}");
        
        context.AddSource("CodeSampleLocator.g.cs", SourceText.From(sb.ToString(), Encoding.UTF8));
    }
    private static void GenerateHelperMethods(SourceProductionContext context, SamplerMetadata metadata)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated />");
        sb.AppendLine("#nullable enable");
        sb.AppendLine("using System.Collections.Immutable;");
        sb.AppendLine();
        sb.AppendLine("namespace NetCordSampler.Generated;");
