// DTOs for deserializing SamplerTypes.json
internal class SamplerMetadata
{
    public TypeMetadataDto[] Types { get; set; } = [];
}

internal class TypeMetadataDto
{
    public string FullType { get; set; } = string.Empty;
    public string Description { get; set; } = string.Empty;
    public string? SourceSummary { get; set; }
    public string Category { get; set; } = string.Empty;
    public ConstructorParamDto[]? ConstructorParams { get; set; }
    public PropertyMetadataDto[]? Properties { get; set; }
    public LimitationDto[]? Limitations { get; set; }
}

internal class ConstructorParamDto
{
    public string Name { get; set; } = string.Empty;
    public string Type { get; set; } = string.Empty;
    public bool HasDefaultValue { get; set; }
    public string? DefaultValue { get; set; }
    public List<string>? InterfaceImplementations { get; set; }
}

internal class PropertyMetadataDto
{
    public string Name { get; set; } = string.Empty;
    public string Type { get; set; } = string.Empty;
    public string? Description { get; set; }
    public string? SourceSummary { get; set; }
    public string? ConfigKey { get; set; }
    public string? DefaultValue { get; set; }
    public bool NestedSample { get; set; }
    public string? CollectionOf { get; set; }
    public int? DefaultCount { get; set; }
    public int? MaxLength { get; set; }
}

internal class LimitationDto
{
    public string Name { get; set; } = string.Empty;
    public string? Description { get; set; }
    public string? Value { get; set; }
    public int Min { get; set; }
    public int Max { get; set; }
}

